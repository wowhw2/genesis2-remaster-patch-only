  function 이착륙시작(방향, 시작y, 프레임) {
    return { 방향: 방향, y: (시작y | 0), 속도: 0, 프레임: 프레임 | 0, i: 0,
             소리: 이동연출.엔진소리 };      /* 시작할 때 한 번 (0x212D0 · 0x2040A) */
  }
  /** 이·착륙 한 프레임. 더 돌 것이 있으면 true (`0x212D5` · `0x2040F` 루프) */
  function 이착륙전진(s) {
    var T = Math.trunc;
    s.소리 = null;
    if (s.방향 === '이륙') { if (s.y < 0) return false; }                  /* 0x2130C */
    else                   { if (s.y > 이동연출.착륙끝y) return false; }   /* 0x2044E */
    var 걸음 = T(s.속도);                                        /* 0x39980 fistp — 절삭 */
    s.y += (s.방향 === '이륙') ? -걸음 : 걸음;
    s.속도 += 이동연출.가속;
    s.i++;
    return true;
  }

