/**
 * 월드 십자 — 누른 방향에서 가장 가까운 지점 (설계서 4절)
 *   그 방향 ±45° 안에 있는 지점만 본다. 거리에 «옆으로 벗어난 만큼»을 두 배로 더해 곧은 쪽을 먼저 고른다.
 * @param {{x,y}} 지금 지금 커서 지점 자리
 * @param {Array<{x,y}>} 지점들
 * @param {string} 방향 '위'·'아래'·'왼쪽'·'오른쪽'
 * @param {number} 지금번호 지금 지점 번호(자기 자신은 뺀다) · 없으면 −1
 * @returns {number} 고른 번호 · 그쪽에 없으면 −1
 */
function 방향지점(지금, 지점들, 방향, 지금번호) {
  var d = { 위: [0, -1], 아래: [0, 1], 왼쪽: [-1, 0], 오른쪽: [1, 0] }[방향];
  if (!d || !지금 || !지점들) return -1;
  var 최선 = -1, 최소 = Infinity;
  for (var i = 0; i < 지점들.length; i++) {
    if (i === 지금번호 || !지점들[i]) continue;
    var dx = 지점들[i].x - 지금.x, dy = 지점들[i].y - 지금.y;
    var 앞 = dx * d[0] + dy * d[1], 옆 = Math.abs(dx * d[1] - dy * d[0]);
    if (앞 <= 0 || 옆 > 앞) continue;                 /* ±45° 밖 */
    var 점수 = 앞 + 옆 * 2;
    if (점수 < 최소) { 최소 = 점수; 최선 = i; }
  }
  return 최선;
}

