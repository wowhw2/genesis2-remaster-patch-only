/**
 * VGA 6비트 팔레트(0~63) → 8비트 RGB
 *
 * ★★★★★ **0~103 색은 `GENESIS.PAL` 이 덮는다** (2026-09-03 · 사용자 지적)
 *
 *   > 사용자: 「**팔레트가 다르겠지**」 (원본에 없는 **빨간 갈고리**가 간판·집 모서리에)
 *
 *   ☠ 맵 팔레트의 그 자리는 **`(63,0,0)` 순수 빨강**이다 — 「비워 둔 자리」다.
 *     `CLIPS.MAP` 실측: **96~103 · 112~119 · 128~151 · 184~191** 이 전부 `(63,0,0)`.
 *     그런데 오브젝트 그림은 그 색인을 **실제로 쓴다** — `#95 24×64` 를 찍어 보면
 *     네 모서리에 **갈고리 모양**으로 박혀 있고, 사용자 화면의 빨간 갈고리와 같다.
 *
 *   ★ `GENESIS.PAL` 의 96~103 은 **밝은 갈색 그라데이션**이다 —
 *     `(62,55,43) (56,48,39) (48,40,34) (40,32,29) (32,25,23) (24,19,18) (16,11,11) (8,5,5)`
 *     ⇒ 지붕·나무 모서리에 딱 맞는 색이다.
 *
 *   ★★ 전투 렌더러가 **이미 그렇게 한다** — `native.js:1179`
 *     `palette.set(basePalette.subarray(0, 312), 0);  // 0~103색 = GENESIS.PAL`
 *     마을만 안 하고 있었다.
 *
 * @param {Uint8Array} pal   맵 팔레트 768 B (6 비트)
 * @param {Uint8Array} [기본] `GENESIS.PAL` 768 B (6 비트) — 앞 104 색을 덮는다
 */
function 팔레트만들기(pal, 기본) {
  var out = new Uint8Array(256 * 4);
  if (기본 && 기본.length >= 312) {
    pal = new Uint8Array(pal);                 /* 원본을 안 건드린다 */
    pal.set(기본.subarray(0, 312), 0);         /* ★ 0~103 색 (104 × 3 = 312) */
  }
  for (var i = 0; i < 256; i++) {
    /* 6비트를 8비트로: (v << 2) | (v >> 4) — 63 이 255 가 된다 */
    /* ★ 63 — **VGA DAC 6비트**(0~63). 원본 `.PCX` 팔레트가 그 범위로 온다. */
    var r = pal[i * 3] & 63, g = pal[i * 3 + 1] & 63, b = pal[i * 3 + 2] & 63;
    out[i * 4]     = (r << 2) | (r >> 4);
    out[i * 4 + 1] = (g << 2) | (g >> 4);
    out[i * 4 + 2] = (b << 2) | (b >> 4);
    out[i * 4 + 3] = 255;
  }
  return out;
}

